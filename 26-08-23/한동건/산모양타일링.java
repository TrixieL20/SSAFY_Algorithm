class Solution {
    public int solution(int n, int[] tops) {
        final int MOD = 10007;

        // dp1[i]: i번째 위치까지 채웠을 때, "오른쪽으로 아무것도 안 걸치고
        //          깔끔하게 마무리된" 상태의 경우의 수
        // dp2[i]: i번째 위치까지 채웠을 때, "오른쪽 삼각형과 마름모를 만들
        //          여지를 남겨둔" 상태의 경우의 수
        long[] dp1 = new long[n];
        long[] dp2 = new long[n];

        // ===== base case (i = 0) =====
        // 첫 번째 아래쪽 삼각형만 있을 때
        // dp1[0] = 1  : 딱 삼각형 하나로 채우는 경우 1가지
        // dp2[0] = 2 + tops[0]
        //   -> top이 없으면 기본 2가지 (오른쪽에 열어둔 채로 끝나는 방식)
        //   -> top이 있으면(tops[0]==1) 위에 붙은 삼각형과 결합하는 경우가
        //      1가지 더 생겨서 +1
        dp1[0] = 1;
        dp2[0] = (2 + tops[0]) % MOD;

        // ===== 점화식 진행 (i = 1 ~ n-1) =====
        for (int i = 1; i < n; i++) {

            // dp1[i]는 직전 상태가 dp1이었든 dp2였든 상관없이
            // "이번 칸에서 오른쪽으로 안 걸치고 마무리"하면 되므로
            // 그냥 두 상태를 더한다.
            dp1[i] = (dp1[i - 1] + dp2[i - 1]) % MOD;

            // dp2[i]는 이번 칸을 "오른쪽에 걸치는 형태"로 마무리하는 경우인데,
            // top[i] 유무에 따라 선택 가능한 조합 수가 달라진다.
            //   - 직전이 dp1(깔끔히 끝난 상태)이었다면: top 없으면 1가지, 있으면 2가지 → (1+tops[i])
            //   - 직전이 dp2(이미 걸쳐진 상태)였다면: top 없으면 2가지, 있으면 3가지 → (2+tops[i])
            dp2[i] = (dp1[i - 1] * (1 + tops[i])
                    + dp2[i - 1] * (2 + tops[i])) % MOD;
        }

        // 마지막 칸에서 두 상태(깔끔히 끝남 + 걸쳐서 끝남) 모두
        // "전체 도형을 다 채운" 유효한 경우이므로 둘을 더해서 반환
        return (int) ((dp1[n - 1] + dp2[n - 1]) % MOD);
    }
}